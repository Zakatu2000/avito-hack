const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('../.local/browser/node_modules/playwright')

async function runPortalFlows(page, base, internEmail, internPassword) {
  const go = (url) => page.goto(base + url)
  const button = (name) => page.getByRole('button', { name, exact: true })
  await page.setViewportSize({ width: 1100, height: 900 })
  await go('/requests/new/technical_support')
  await page.getByLabel('Категория').selectOption('environment')
  await page.getByLabel('Заголовок').fill('Стенд Chromium')
  await page.getByLabel('Описание', { exact: true }).fill('Тестовый стенд не запустился')
  await page.getByLabel('Связанная задача').selectOption('wk2-docs')
  await button('Сохранить черновик').click()
  await page.waitForURL('**/requests#*')
  await page.getByRole('link', { name: 'Редактировать и отправить' }).click()
  await button('Отправить заявку').click()
  await page.waitForURL('**/requests#*')
  const supportAnchor = new URL(page.url()).hash
  await go('/requests/new/mentor_consultation')
  await page.getByLabel('Тема', { exact: true }).fill('Старт Chromium')
  await page.getByLabel('Описание', { exact: true }).fill('Проверка согласования даты')
  await page.getByLabel('Предпочтительная дата и время').fill('2099-01-02T10:30')
  await button('Отправить заявку').click()
  await page.waitForURL('**/requests#*')
  await go('/requests/new/learning_request')
  await page.getByLabel('Тема', { exact: true }).fill('Микросервисы')
  await button('Найти материалы').click()
  await page.getByRole('heading', { name: /микросервис/i }).first().waitFor()
  await page.getByLabel('Причина запроса').fill('Изучение архитектуры учебной задачи')
  await button('Отправить заявку').click()
  await page.waitForURL('**/requests#*')

  async function login(email, password) {
    await button('Выйти').click()
    await page.waitForURL('**/login')
    await page.getByLabel('Email', { exact: true }).fill(email)
    await page.getByLabel('Пароль', { exact: true }).fill(password)
    await button('Войти').click()
    await page.waitForURL(base + '/')
  }

  await go('/timeline')
  const quick = page.locator('.quick-start')
  await quick.getByRole('button', { name: 'Начать', exact: true }).first().click()
  await quick.getByRole('button', { name: 'Готово', exact: true }).click()
  await quick.getByRole('button', { name: 'Начать', exact: true }).click()
  await quick.getByRole('button', { name: 'На проверку', exact: true }).click()
  await go('/chat')
  await page.setViewportSize({ width: 390, height: 844 })
  await button('+ Новый чат').click()
  await page.route('**/api/chat', async (route) => {
    await route.fulfill({ status: 503, json: { code: 'UNAVAILABLE', message: 'Провайдер недоступен' } })
    await page.unroute('**/api/chat')
  })
  const chat = page.getByRole('textbox', { name: 'Сообщение боту' })
  await chat.fill('VPN (ошибка')
  await chat.press('Shift+Enter')
  assert.match(await chat.inputValue(), /\n$/)
  await chat.press('Enter')
  await page.getByRole('alert').filter({ hasText: 'Провайдер недоступен' }).waitFor()
  await button('Повторить').click()
  await page.getByRole('link', { name: 'Создать техническое обращение' }).waitFor()
  assert.equal(await page.locator('.msg--user').count(), 1)
  await button('Решено').click()
  await page.getByText('Отзыв сохранён').waitFor()
  await page.reload()
  await page.getByText('Отзыв сохранён').waitFor()
  await page.getByRole('link', { name: 'Создать техническое обращение' }).waitFor()
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark' })
  assert.equal(await page.evaluate(() => getComputedStyle(document.querySelector('.chat__log')).overflowY), 'auto')

  if (process.env.BROWSER_MENTOR_EMAIL) {
    await page.setViewportSize({ width: 1100, height: 900 })
    await login(process.env.BROWSER_MENTOR_EMAIL, process.env.BROWSER_MENTOR_PASSWORD)
    await go('/chat')
    await page.getByRole('button', { name: '+ Новый чат' }).waitFor()
    assert.equal((await (await page.request.get(base + '/api/chats')).json()).length, 0)
    await go('/team')
    const internCard = page.locator('.card').filter({ has: page.getByRole('heading', { name: 'Анна Проверка' }) })
    await internCard.getByRole('button', { name: 'Назначить учебную задачу' }).click()
    const mentorQueue = page.getByRole('region', { name: 'Пункты на подтверждение' })
    await mentorQueue.getByRole('button', { name: 'Подтвердить', exact: true }).click()
    await button('Взять в работу').click()
    await button('Предложить решение').click()
    await page.getByLabel('Результат', { exact: true }).fill('Проверено в браузере')
    await button('Сохранить').click()
    await button('Подтвердить время').click()
    await button('Завершить консультацию').click()
    await page.getByLabel('Результат', { exact: true }).fill('Результат встречи')
    await button('Сохранить').click()
    await button('Сохранить рекомендацию').click()
    await page.getByLabel('Результат', { exact: true }).fill('Изучить Playbook')
    await page.getByLabel('Ссылка на рекомендацию').fill('https://github.com/avito-tech/playbook')
    await button('Сохранить').click()
    const internContext = await page.context().browser().newContext()
    try {
      const internLogin = await internContext.request.post(base + '/api/auth/login', { data: { email: internEmail, password: internPassword } })
      const internCsrf = (await internLogin.json()).csrfToken
      const mentorCsrf = (await (await page.request.get(base + '/api/auth/session')).json()).csrfToken
      for (const system of ['confluence', 'jira', 'repo']) {
        const access = await internContext.request.post(base + '/api/requests/access', {
          headers: { 'X-CSRF-Token': internCsrf },
          data: { system, durationDays: 30, justification: 'Проверка быстрого старта в Chromium' },
        })
        assert.equal(access.status(), 201)
        const ticket = await access.json()
        for (const expected of ['approving', 'approved']) {
          const approval = await page.request.post(base + '/api/requests/' + ticket.id + '/approve', {
            headers: { 'X-CSRF-Token': mentorCsrf },
          })
          assert.equal((await approval.json()).status, expected)
        }
      }
    } finally { await internContext.close() }
    await login(internEmail, internPassword)
    await go('/requests' + supportAnchor)
    await button('Закрыть обращение').click()
    await page.getByText('Проверено в браузере').first().waitFor()
    await go('/chat')
    await page.getByRole('button', { name: 'VPN (ошибка', exact: true }).click()
    await page.getByText('Отзыв сохранён').waitFor()
    await go('/timeline')
    await quick.getByRole('button', { name: 'Начать', exact: true }).click()
    await quick.getByRole('button', { name: 'Готово', exact: true }).click()
    await quick.getByRole('button', { name: 'Открыть учебную задачу', exact: true }).click()
    await quick.getByRole('heading', { name: 'Разобрать тесты учебного сервиса' }).waitFor()
    await quick.getByRole('button', { name: 'Отметить начало работы', exact: true }).click()
    await login(process.env.BROWSER_MENTOR_EMAIL, process.env.BROWSER_MENTOR_PASSWORD)
    await go('/team')
    await internCard.getByRole('button', { name: 'Подтвердить старт' }).click()
    await internCard.getByText('Самостоятельный старт подтверждён').waitFor()
    await login(internEmail, internPassword)
    await go('/timeline')
    await page.getByText('5 из 5 шагов').waitFor()
  }
  console.log('Portal smoke: request forms, quick start, mobile chat retry, feedback and account isolation passed')
}

async function runContactNavigator(page, base) {
  await page.setViewportSize({ width: 1200, height: 900 })
  await page.goto(base + '/contacts')
  const search = page.getByRole('searchbox', { name: 'Что случилось?' })
  const recommendation = page.getByRole('region', { name: 'Рекомендация' })
  await search.fill('Нужен доступ и не работает VPN')
  const category = recommendation.getByRole('button', { name: 'Техническая проблема' })
  await category.focus()
  await category.press('Enter')
  await recommendation.getByRole('heading', { name: 'Техническая помощь' }).waitFor()
  const list = async () => (await page.request.get(base + '/api/requests')).json()
  const before = await list()
  await recommendation.getByRole('link', { name: 'Создать обращение' }).click()
  assert.equal(await page.getByLabel('Категория').inputValue(), 'network')
  assert.deepEqual(await list(), before)
  await page.getByLabel('Заголовок', { exact: true }).fill('Проверка VPN')
  await page.getByLabel('Описание', { exact: true }).fill('Тестовая сеть не отвечает')
  await page.getByRole('button', { name: 'Отправить заявку', exact: true }).click()
  await page.waitForURL('**/requests#*')
  assert.equal((await list()).length, before.length + 1)

  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(base + '/contacts')
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'], { origin: base })
  await search.fill('не работает VPN')
  await recommendation.getByRole('button', { name: 'Подготовить сообщение' }).click()
  const message = page.getByRole('textbox', { name: 'Текст сообщения' })
  assert(await message.evaluate((el) => document.activeElement === el))
  await message.fill('Синтетическое сообщение для проверки')
  await page.getByRole('button', { name: 'Скопировать текст' }).click()
  await page.getByText('Скопировано', { exact: true }).waitFor()
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), 'Синтетическое сообщение для проверки')
  await page.getByRole('button', { name: 'Закрыть черновик' }).click()
  for (const theme of ['light', 'dark']) {
    await page.evaluate((value) => { document.documentElement.dataset.theme = value }, theme)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
    assert(await recommendation.isVisible())
  }
  await page.setViewportSize({ width: 1200, height: 900 })
  console.log('Contact navigator: keyboard, VPN form, explicit submit, clipboard, mobile and themes passed')
}

async function main() {
  let executablePath = process.env.CHROMIUM_PATH || chromium.executablePath()
  if (!fs.existsSync(executablePath) && process.env.LOCALAPPDATA) {
    const root = path.join(process.env.LOCALAPPDATA, 'ms-playwright')
    const versions = fs.readdirSync(root).filter((v) => /^chromium-\d+$/.test(v)).sort().reverse()
    executablePath = path.join(root, versions[0], 'chrome-win64', 'chrome.exe')
  }
  const browser = await chromium.launch({ headless: true, executablePath })
  try {
    const context = await browser.newContext()
    const page = await context.newPage()
    const base = process.env.BASE_URL || 'http://localhost:5177'
    const email = `browser-${Date.now()}@example.test`
    const password = 'browser-check-password-2026'
    const errors = []
    page.on('pageerror', (e) => errors.push(e.message))
    await page.goto(`${base}/login`)
    await page.getByRole('button', { name: 'Создать аккаунт', exact: true }).click()
    await page.getByLabel('Имя и фамилия').fill('Анна Проверка')
    await page.getByLabel('Email', { exact: true }).fill(email)
    await page.getByLabel('Пароль', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'Зарегистрироваться' }).click()
    await page.getByText('Привет, Анна', { exact: false }).waitFor()
    assert.equal(await page.evaluate(() => localStorage.getItem('ai-buddy-auth')), null)
    assert.equal(await page.evaluate(() => navigator.serviceWorker.controller), null)
    const cookie = (await context.cookies()).find((c) => c.name === 'buddy_session')
    assert(cookie?.httpOnly && cookie.sameSite === 'Strict')
    for (const route of ['/timeline', '/contacts', '/kb', '/metrics', '/requests']) {
      await page.goto(base + route)
      await page.locator('.page h1').waitFor()
      await page.waitForLoadState('networkidle')
      assert(!await page.getByText('Сервис вернул данные в неожиданном формате').count(), route)
    }
    await page.goto(`${base}/requests/new/access`)
    await page.getByLabel('Система', { exact: true }).selectOption('confluence')
    await page.getByLabel('Для какой задачи нужен доступ').fill('Для чтения документации команды')
    await page.getByRole('button', { name: 'Предпросмотр и отправка' }).click()
    await page.getByRole('button', { name: 'Сохранить черновик' }).click()
    await page.waitForURL('**/requests')
    await page.getByText('Доступ: confluence', { exact: true }).waitFor()
    await page.reload()
    await page.getByText('Доступ: confluence', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Отправить', exact: true }).click()
    await page.getByText('Отправлен', { exact: true }).first().waitFor()
    await page.goto(`${base}/chat`)
    const chatInput = page.locator('textarea, input').filter({ visible: true }).first()
    await chatInput.fill('Что дальше по плану?')
    await chatInput.press('Enter')
    await page.getByText('Следующий шаг:', { exact: false }).waitFor()
    await page.reload()
    await page.getByText('Следующий шаг:', { exact: false }).waitFor()
    const q = page.getByRole('textbox', { name: 'Сообщение боту' })
    await q.fill('Где изучить микросервисы?')
    await page.getByRole('button', { name: 'Отправить', exact: true }).click()
    await page.locator('.chat-sources li').first().waitFor()
    await page.goto(`${base}/team`)
    await page.getByText('Нет доступа', { exact: true }).waitFor()
    await page.goto(`${base}/`)
    await page.getByRole('button', { name: 'Выйти', exact: true }).click()
    await page.waitForURL('**/login')
    assert.equal((await context.request.get(base + '/api/auth/session')).status(), 401)
    await page.getByLabel('Email', { exact: true }).fill(email)
    await page.getByLabel('Пароль', { exact: true }).fill('incorrect-password')
    await page.getByRole('button', { name: 'Войти', exact: true }).click()
    await page.getByRole('alert').filter({ hasText: 'Неверный email или пароль' }).waitFor()
    await page.getByLabel('Пароль', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'Войти', exact: true }).click()
    await page.getByText('Привет, Анна', { exact: false }).waitFor()
    await page.reload()
    await page.getByText('Привет, Анна', { exact: false }).waitFor()
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(`${base}/requests`)
    await page.getByText('Доступ: confluence', { exact: true }).waitFor()
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
    if (process.env.BROWSER_EXTENDED === '1') await runPortalFlows(page, base, email, password)
    await runContactNavigator(page, base)
    assert.deepEqual(errors, [])
    console.log('Browser smoke: registration, login, logout, reload, pages, access request, chat, RBAC and mobile passed')
    await context.close()
  } finally {
    await browser.close()
  }
}
main().catch((error) => { console.error(error); process.exitCode = 1 })
